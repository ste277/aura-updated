// AURA-PALM-D6-I1 -- writes library/packaged-content.mjs: the two pinned C1 rev. 4 library files as string constants,
// so the SAME loader (src/packaged.mjs) runs in Node and in a browser bundle with no file-system access.
// The JSON files stay the source of truth; test/browser-loader.test.mjs fails if the module is not byte-identical.
//   node packages/palm-reading-engine/e1/library/generate-packaged-content.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const read = (name) => readFileSync(new URL(`./${name}.json`, import.meta.url), 'utf8');
export function packagedContentSource() {
  return '// GENERATED by library/generate-packaged-content.mjs from catalogue.json and schema.json -- DO NOT EDIT.\n'
    + '// The exact UTF-8 text of the two pinned C1 rev. 4 files; src/packaged.mjs checks their SHA-256 digests at load.\n'
    + `export const CATALOGUE_TEXT = ${JSON.stringify(read('catalogue'))};\n`
    + `export const SCHEMA_TEXT = ${JSON.stringify(read('schema'))};\n`;
}
if (process.argv[1] && new URL(import.meta.url).pathname === process.argv[1]) writeFileSync(new URL('./packaged-content.mjs', import.meta.url), packagedContentSource());
